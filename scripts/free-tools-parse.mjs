// Parses docs/free-tools-naming.md into src/lib/free-tools/data.generated.json.
// Run: node scripts/free-tools-parse.mjs
import { readFileSync, writeFileSync } from "node:fs";

// Windows checkouts may have CRLF line endings: split on both.
const md = readFileSync("docs/free-tools-naming.md", "utf8").split(/\r?\n/);
const tools = [];
let category = "";
let cur = null;
for (const line of md) {
  const h2 = line.match(/^## (.+)/);
  if (h2) { category = h2[1].trim(); continue; }
  const h3 = line.match(/^### \d+\. (.+)/);
  if (h3) { cur = { name: h3[1].trim(), category, pages: [], faq: [] }; tools.push(cur); continue; }
  if (!cur) continue;
  const f = line.match(/^- \*\*([^:*]+?):?\*\*:?\s*(.*)$/);
  if (!f) continue;
  const key = f[1].toLowerCase(), val = f[2].trim();
  if (key === "subdomain") cur.subdomain = val.replace(/`/g, "").replace(".lazur.app", "");
  else if (key === "title") cur.title = val;
  else if (key === "h1") cur.h1 = val;
  else if (key === "tagline") cur.tagline = val;
  else if (key === "pages") cur.pages = [...val.matchAll(/`\/([a-z0-9-]+)`/g)].map((m) => m[1]);
  else if (key.startsWith("faq"))
    cur.faq = val.split(" · ").map((q) => ({ q: q.replace(/\s*\*\(drafted\)\*/, "").trim(), drafted: /drafted/.test(q) }));
}
writeFileSync("src/lib/free-tools/data.generated.json", JSON.stringify(tools, null, 1));
console.log(tools.length, "tools;", tools.reduce((n, t) => n + t.pages.length, 0), "pages");
const bad = tools.filter((t) => !t.subdomain || !t.title || !t.h1 || !t.tagline);
if (bad.length) console.log("missing fields:", bad.map((t) => t.name));
console.log(tools.map((t) => t.subdomain).join(" "));

// Keep the Worker's list of served subdomains in sync.
writeFileSync(
  "edge/src/tool-subdomains.ts",
  `// Generated by scripts/free-tools-parse.mjs from docs/free-tools-naming.md. Do not edit by hand.\n// Free-tool subdomains the Worker serves from the website (docs/free-tools-build-plan.md).\nexport const TOOL_SUBDOMAINS = ${JSON.stringify(tools.map((t) => t.subdomain), null, 2)};\n`,
);
